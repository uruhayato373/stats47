export function geoThumbnailKey(
  dataId: string,
  version: string,
  variant: GeoThumbnailVariant
) {
  return `app/geo/datasets/${dataId}/thumbnails/${version}/${variant}.webp`;
}
export function findGeoSourceThumbnail(dataId: string, version?: string) {
  const config = GEO_SOURCE_THUMBNAILS[dataId];
  return config && config.version === version ? config : null;
}
