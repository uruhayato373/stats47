/**
 * カテゴリマスタ (data/categories/categories.json) から、キーの型 CategoryKey と一覧 CATEGORY_KEYS を
 * src/category-keys.generated.ts に生成する。指標の category はこの型で縛られ、存在しないキーはコンパイルで止まる。
 *
 * 使い方:
 *   tsx packages/data-configs/scripts/build-category-keys.ts
 *   tsx packages/data-configs/scripts/build-category-keys.ts --check   (古さと JSON の不整合を止める)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { datasetPath } from "../../../config/datasets.mjs";
import { PACKAGE_ROOT, REPO_ROOT } from "./_lib.js";

const OUTPUT_FILE = resolve(PACKAGE_ROOT, "src/category-keys.generated.ts");
const KEY_PATTERN = /^[a-z]+$/;

interface CategoryRow {
  key: string;
  name: string;
}

function readCategories(): CategoryRow[] {
  const doc = JSON.parse(readFileSync(resolve(REPO_ROOT, datasetPath("categories.master")), "utf-8")) as {
    categories: CategoryRow[];
  };
  return doc.categories;
}

/** 型の元になるので、重複と形の崩れはここで止める (Schema はキーの重複を表せない) */
function validate(rows: readonly CategoryRow[]): string[] {
  const errors: string[] = [];
  const keys = new Set<string>();
  const names = new Set<string>();
  for (const { key, name } of rows) {
    if (!KEY_PATTERN.test(key)) errors.push(`key が小文字の英字でない: ${key}`);
    if (keys.has(key)) errors.push(`key が重複: ${key}`);
    if (names.has(name)) errors.push(`name が重複: ${name}`);
    keys.add(key);
    names.add(name);
  }
  return errors;
}

function render(rows: readonly CategoryRow[]): string {
  const lines = rows.map(({ key }) => `  ${JSON.stringify(key)},`).join("\n");
  return `/**
 * AUTOGENERATED by scripts/build-category-keys.ts from data/categories/categories.json.
 * DO NOT EDIT MANUALLY. Run \`npm run build:category-keys --workspace=@stats47/data-configs\` to regenerate.
 *
 * 依存を持たない (何も import しない)。middleware が Edge で軽く読めるよう、指標の一覧を巻き込まない subpath
 * \`@stats47/data-configs/category-keys\` から引ける。
 */
export const CATEGORY_KEYS = [
${lines}
] as const;

export type CategoryKey = (typeof CATEGORY_KEYS)[number];
`;
}

function main() {
  const check = process.argv.includes("--check");
  const rows = readCategories();
  const errors = validate(rows);
  if (errors.length > 0) {
    for (const e of errors) console.error(`[category-keys] ${e}`);
    process.exit(1);
  }
  const next = render(rows);
  if (check) {
    let current = "";
    try {
      current = readFileSync(OUTPUT_FILE, "utf-8");
    } catch {
      // 無い場合は stale として扱う
    }
    if (current !== next) {
      console.error(`[category-keys] stale: ${datasetPath("categories.master")} (${rows.length} 件) と src/category-keys.generated.ts が合わない`);
      console.error("[category-keys] fix: npm run build:category-keys --workspace=@stats47/data-configs");
      process.exit(1);
    }
    console.log(`[category-keys] fresh: ${rows.length} categories`);
    return;
  }
  writeFileSync(OUTPUT_FILE, next);
  console.log(`[category-keys] built with ${rows.length} categories`);
}

main();
