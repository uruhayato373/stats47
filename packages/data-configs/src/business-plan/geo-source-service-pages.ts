const field = (
  key: string,
  label: string,
  description: string,
  unit?: string
): GeoSourceField => ({
  key,
  label,
  description,
  ...(unit ? { unit } : {}),
  ...(codeValues[key] ? { values: codeValues[key] } : {}),
});
const variant = (
  key: string,
  label: string,
  description: string,
  unit?: string
): GeoSourceField => ({
  ...field(key, label, description, unit),
  onlyWhenPresent: true,
});

