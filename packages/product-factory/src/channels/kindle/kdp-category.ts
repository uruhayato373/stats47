/**
 * KDP の掲載場所 (最大 3 枠) の SSOT。
 *
 * ★階層は 3 段の select + **掲載場所のチェックボックス** (2026-08-12 に実モーダルを操作して確定)
 *     Kindle本 ─ top (社会・政治) ─ sub (社会学) ─ ☑ place (参考図書・白書)
 *   select を 3 段選んだだけでは「0 個のカテゴリーを選択済み」のままで、
 *   **チェックボックスを入れて初めて 1 枠**になる。ここを取り違えると、
 *   ログ上は選べたように見えて 1 枠も保存されない。
 *
 * ★もとの SSOT は実在しない値だった
 *   `Kindleストア > Kindle本 > ビジネス・経済 > 統計学` という文字列 1 本だったが、
 *   「統計学」という掲載場所は KDP に無い。実在する値だけを持つため 3 段の形にし、
 *   採取済みの分類表 (`kdp-category-tree.json`) と突き合わせるテストを置いた。
 *
 * ★カテゴリは必須。人手に委ねられない
 *   未選択だと「保存して続行」が
 *   「本のカテゴリーを追加します。」で止まり、ウィザードが 1 歩も進まない。
 *   「カテゴリだけ人手」という切り分けは成立しないので SSOT 化して自動選択する。
 *
 * 補足: カテゴリボタンは「成人向けコンテンツ」のラジオを選ぶまで `disabled`。
 *   フォーム側でラジオを先に選んでから開く (kdp-form.mjs)。
 */

/** 1 枠ぶんの掲載場所。`Kindle本` は全枠共通なので持たない。 */
export interface KdpCategoryPath {
  /** select 2 段目 (例: 社会・政治)。 */
  readonly top: string;
  /** select 3 段目 (例: 社会学)。 */
  readonly sub: string;
  /** 掲載場所のチェックボックス (例: 参考図書・白書)。**ここを入れて初めて 1 枠**。 */
  readonly place: string;
}

