/**
 * 漢数字→算用数字 変換の対照テスト。
 *
 * 書籍の書き下ろし章が漢数字で数値を書いていたため、SSOT との機械照合ができなかった
 * (2026-08-12)。算用数字に統一すれば照合できるが、**誤変換は本文を壊す**ので
 * 「変換するもの」と同じ強さで「変換してはいけないもの」を固定する。
 */
import { describe, expect, it } from "vitest";
import { convertKanjiNumerals } from "../kanji-numeral";

const conv = (s: string): string => convertKanjiNumerals(s).text;

describe("convertKanjiNumerals — 数値の主張は算用数字にする", () => {
  it("★書籍に実在した金額表現", () => {
    expect(conv("東京都は五百二十一万四千円で")).toBe("東京都は5,214,000円で");
    expect(conv("沖縄県は二百十六万七千円と")).toBe("沖縄県は2,167,000円と");
    expect(conv("山形県は月額五十四万五千円で")).toBe("山形県は月額545,000円で");
    expect(conv("家賃は月二万一千円と")).toBe("家賃は月21,000円と");
  });

  it("順位は常に算用数字にする", () => {
    expect(conv("全国一位に立ち")).toBe("全国1位に立ち");
    expect(conv("それより十位以上も低い")).toBe("それより10位以上も低い");
    expect(conv("一位から四十七位まで")).toBe("1位から47位まで");
  });

  it("倍率・割合", () => {
    expect(conv("実に八倍以上の開き")).toBe("実に8倍以上の開き");
    expect(conv("三十七％を占める")).toBe("37％を占める");
  });

  it("★漢数字の小数は 1 つの数として扱う", () => {
    expect(conv("両者の間には二・四倍もの開き")).toBe("両者の間には2.4倍もの開き");
  });

  it("大きい単位 (億・兆)", () => {
    expect(conv("六兆円규")).toContain("6,000,000,000,000円");
    expect(conv("三億円")).toBe("300,000,000円");
  });
});

describe("convertKanjiNumerals — 語彙的な漢数字は残す", () => {
  it("★「二人以上の世帯」は家計調査の正式な区分名 (変換すると別語になる)", () => {
    const s = "調査対象が「二人以上の世帯」である点";
    expect(conv(s)).toBe(s);
  });

  it("★「一人当たり」系の固定表現", () => {
    for (const s of [
      "一人当たり県民所得を見ると",
      "従業者一人当たりの出荷額",
      "一世帯あたりの人数",
      "一件あたりの費用",
    ]) {
      expect(conv(s)).toBe(s);
    }
  });

  it("★「同一年」の一を数値にしない (語の一部)", () => {
    expect(conv("同一年、あるいは近い年で")).toBe("同一年、あるいは近い年で");
  });

  it("★「数十年」を「数10年」にしない", () => {
    expect(conv("数十年の時間差でつながる")).toBe("数十年の時間差でつながる");
  });

  it("★算用数字に続く位取り漢字を壊さない (69万人 → そのまま)", () => {
    expect(conv("全国で約69万人の介護人材が")).toBe("全国で約69万人の介護人材が");
  });

  it("一人暮らし・一人で は残す", () => {
    expect(conv("高齢者の一人暮らしは増え")).toBe("高齢者の一人暮らしは増え");
    expect(conv("一人で暮らすのか")).toBe("一人で暮らすのか");
  });

  it("単位が無い漢数字は触らない (第一に・二次産業)", () => {
    expect(conv("第一に、家計調査は")).toBe("第一に、家計調査は");
    expect(conv("第二次産業の比率")).toBe("第二次産業の比率");
  });
});

describe("convertKanjiNumerals — 変換の記録", () => {
  it("何を何に変えたかを返す (目視確認に使う)", () => {
    const r = convertKanjiNumerals("東京都は五百二十一万四千円で全国一位");
    expect(r.conversions.map((c) => [c.before, c.after])).toEqual([
      ["五百二十一万四千円", "5,214,000円"],
      ["一位", "1位"],
    ]);
  });

  it("変換が無ければ本文もそのまま", () => {
    const s = "一人当たりの数値を比較します。";
    const r = convertKanjiNumerals(s);
    expect(r.text).toBe(s);
    expect(r.conversions).toEqual([]);
  });
});

describe("convertKanjiNumerals — 実データで見つかった誤変換の再発防止", () => {
  it("★西暦に桁区切りを入れない (2,040年 は誤り)", () => {
    expect(conv("二〇四〇年をピークに")).toBe("2040年をピークに");
    expect(conv("一九八〇年から")).toBe("1980年から");
  });

  it("★桁を並べた表記を位取りと誤読しない (一四五一万人)", () => {
    expect(conv("約一四五一万人をピークに")).toBe("約14,510,000人をピークに");
  });

  it("★「件/千人」は分母の単位なので残す", () => {
    expect(conv("大阪府(6.65件/千人)を筆頭に")).toBe("大阪府(6.65件/千人)を筆頭に");
  });

  it("★「人口千人あたり」も分母の単位", () => {
    expect(conv("人口千人あたりの転入超過数")).toBe("人口千人あたりの転入超過数");
    expect(conv("人口千人当たりの認知件数")).toBe("人口千人当たりの認知件数");
  });

  it("西暦の範囲外の「年」は桁区切りを入れる (期間など)", () => {
    expect(conv("四十年間の推移")).toBe("40年間の推移");
  });
});
